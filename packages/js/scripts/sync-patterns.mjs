import { copyFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

const here = dirname(fileURLToPath(import.meta.url));

function findPackageRoot(from) {
  let current = from;
  while (current !== dirname(current)) {
    if (existsSync(resolve(current, "package.json"))) {
      return current;
    }
    current = dirname(current);
  }
  throw new Error("Could not find package.json");
}

const packageRoot = findPackageRoot(here);
// packages/js/scripts/sync-patterns.mjs -> the repo root is three levels up.
const repoRoot = resolve(here, "..", "..", "..");

// The shared data files both packages read: the alias table and the data
// tables (src/rolodexter/tables.json). Each is copied byte-for-byte.
const SHARED_FILES = ["patterns.json", "tables.json"];
const pairs = SHARED_FILES.map((name) => ({
  name,
  source: resolve(repoRoot, "src", "rolodexter", name),
  target: resolve(packageRoot, "src", name),
}));

// --check compares the generated copies against the Python sources instead of
// overwriting them. Useful locally if you suspect someone hand-edited the
// generated files, but NOT a CI gate: packages/js/src/*.json is gitignored and
// regenerated by every build, so on a clean checkout they do not exist yet and
// there is no committed copy that could drift.
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  let inSync = true;
  for (const { name, source, target } of pairs) {
    const sourceContents = readFileSync(source);
    let targetContents;
    try {
      targetContents = readFileSync(target);
    } catch {
      targetContents = null;
    }

    if (targetContents === null || !sourceContents.equals(targetContents)) {
      inSync = false;
      console.error(
        `${name} is out of sync:\n` +
          `  source: ${relative(repoRoot, source)}\n` +
          `  target: ${relative(repoRoot, target)}`,
      );
    }
  }

  if (!inSync) {
    console.error(`Run "npm run sync:patterns" to update them.`);
    process.exit(1);
  }

  console.log(`${SHARED_FILES.join(" and ")} are in sync.`);
  process.exit(0);
}

for (const { target, source } of pairs) {
  mkdirSync(dirname(target), { recursive: true });
  copyFileSync(source, target);
}
