from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

if sys.version_info >= (3, 11):
    import tomllib
else:  # Python 3.10
    import tomli as tomllib  # type: ignore[import-not-found, unused-ignore]

ROOT = Path(__file__).resolve().parents[1]


def _read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def _check(errors: list[str], where: str, found: object, expected: str) -> None:
    if found != expected:
        errors.append(f"{where} version {found!r} does not match {expected!r}")


def main() -> int:
    pyproject = tomllib.loads(_read("pyproject.toml"))
    package_json = json.loads(_read("packages/js/package.json"))
    python_version = pyproject["project"]["version"]
    npm_version = package_json["version"]
    errors: list[str] = []

    if python_version != npm_version:
        errors.append(
            f"Python version {python_version!r} does not match NPM version "
            f"{npm_version!r}"
        )

    # packages/js/src/index.ts hardcodes the version it reports from
    # `rolodexter --version` and from the exported `version`/`__version__`.
    # Nothing compared it to package.json, so 2.11.0 shipped to npm reporting
    # itself as 2.10.0. Python reads its version from importlib.metadata and
    # cannot drift this way; the JS literal can, so check it here.
    index_ts = _read("packages/js/src/index.ts")
    match = re.search(r'^export const version = "([^"]+)";', index_ts, re.MULTILINE)
    if match is None:
        errors.append(
            'could not find `export const version = "..."` in packages/js/src/index.ts'
        )
    else:
        _check(errors, "packages/js/src/index.ts", match.group(1), npm_version)

    # The lockfile repeats the package version in two places.
    lock_path = ROOT / "packages/js/package-lock.json"
    if lock_path.exists():
        lock = json.loads(lock_path.read_text(encoding="utf-8"))
        _check(errors, "package-lock.json `version`", lock.get("version"), npm_version)
        _check(
            errors,
            'package-lock.json `packages[""].version`',
            lock.get("packages", {}).get("", {}).get("version"),
            npm_version,
        )
    else:
        errors.append("packages/js/package-lock.json is missing")

    # The alias table carries a version field; the JS copy is generated by the
    # build and is absent on a clean checkout, so only check it when present.
    for rel in ("src/rolodexter/patterns.json", "packages/js/src/patterns.json"):
        if (ROOT / rel).exists():
            _check(errors, rel, json.loads(_read(rel)).get("version"), npm_version)
        elif rel.startswith("src/"):
            errors.append(f"{rel} is missing")

    # Version strings shown on the site and the pricing page.
    index_html = _read("docs/index.html")
    shown = {
        "docs/index.html softwareVersion": re.findall(
            r'"softwareVersion":\s*"([^"]+)"', index_html
        ),
        "docs/index.html page text": re.findall(r"\bv(\d+\.\d+\.\d+)\b", index_html),
    }
    pricing = ROOT / "docs/pricing.md"
    if pricing.exists():
        shown["docs/pricing.md"] = re.findall(
            r"\bv(\d+\.\d+\.\d+)\b", pricing.read_text(encoding="utf-8")
        )
    for where, versions in shown.items():
        if not versions:
            errors.append(f"could not find a version string in {where}")
        for found in versions:
            _check(errors, where, found, npm_version)

    ref_type = os.environ.get("GITHUB_REF_TYPE")
    ref_name = os.environ.get("GITHUB_REF_NAME")
    if ref_type == "tag" and ref_name:
        tag_version = ref_name.removeprefix("v")
        if tag_version != python_version:
            errors.append(
                f"release tag {ref_name!r} does not match package version "
                f"{python_version!r}"
            )

    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1

    print(f"release versions match: {python_version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
